test('workbench service pauses and restores running components and matches standalone location', async t => {
  const h=await fixture(t); await execute(h.vault,capture());
  const events=[], plugin={app:{vault:{adapter:{getBasePath:()=>h.vault},configDir:'.obsidian'}},issues:{root:h.vault}};
  let release=await storage.lease(h.vault);
  plugin.agentBridge={server:{listening:true},async stop(){events.push('bridge-stop');await release();this.server.listening=false;},async start(){events.push('bridge-start');release=await storage.lease(h.vault);this.server.listening=true;}};
  plugin.fns={runtime:{async suspend(){events.push('fns-stop');return {enabled:false};},async restore(){events.push('fns-restore');},async inspect(){return {enabled:false,loaded:false};}}};
  const service=new RuntimeSettings(plugin), plan=await service.inspect(h.vault,'local/runtime');
  const result=await service.apply(h.vault,{plan,directory:'local/runtime',backup:path.join(h.base,'ui-backup')});
  assert.equal(result.runtime,'local/runtime'); assert.deepEqual(result.warnings,[]);
  assert.deepEqual(events,['bridge-stop','fns-stop','fns-restore','bridge-start']);
  assert.equal((await service.inspect(h.vault)).current,'local/runtime'); await release();
});
