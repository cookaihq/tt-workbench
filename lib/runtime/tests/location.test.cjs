test('failure after copy or cleanup blocks writes and can resume or restore from the same backup', async t => {
  for(const step of ['afterCopy','beforeCommit']) {
    const h=await fixture(t), request=capture(); await execute(h.vault,request);
    const backup=path.join(h.base,'recovery');
    await assert.rejects(h.change('local/runtime',{backup,[step](){throw Error('injected');}}),/injected/);
    assert.equal(storage.relative('',h.vault),storage.ROOT);
    await assert.rejects(execute(h.vault,request),{code:'RUNTIME_BUSY'});
    const options={vault:h.vault,backup,writersStopped:true};
    assert.equal((await migration.migrate({...options,restore:true})).status,'restored');
    assert.equal((await execute(h.vault,request)).reused,true);
    assert.equal((await migration.migrate({...options,resume:true})).status,'complete');
    assert.equal((await execute(h.vault,request)).reused,true);
    await execute(h.vault,capture());
    await assert.rejects(migration.migrate({...options,restore:true}),{code:'SOURCE_CHANGED'});
  }
});
test('hard exit after pointer commit resumes with fixed gate and refuses foreign backup', async t => {
  const h=await fixture(t); await execute(h.vault,capture());
  const options={vault:h.vault,directory:'local/runtime',backup:path.join(h.base,'crash'),writersStopped:true,configureIsolation:true};
  options.expected=(await migration.inspect(options)).fingerprint;
  const code=`require(${JSON.stringify(path.join(repo,'lib/runtime/migrate.cjs'))}).migrate({...${JSON.stringify(options)},afterCommit(){process.exit(73)}}).catch(()=>process.exit(74))`;
  await assert.rejects(exec(process.execPath,['-e',code]),e=>e.code===73);
  await assert.rejects(storage.lease(h.vault),{code:'RUNTIME_BUSY'});
  assert.equal((await migration.migrate({...options,resume:true})).status,'complete');
  assert.equal((await migration.inspect({vault:h.vault})).status,'ready');
  const second=await fixture(t);
  await assert.rejects(migration.migrate({...options,vault:second.vault,resume:true}),{code:'INVALID_MANIFEST'});
});
