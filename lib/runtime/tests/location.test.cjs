async function fixture(t) {
  const parent = path.join(repo, 'tmp/runtime-location-tests'); await fs.mkdir(parent, { recursive: true });
  const base = await fs.mkdtemp(path.join(parent, 'case-')), vault = path.join(base, 'vault'); await fs.mkdir(vault);
  t.after(async () => { assert.equal(path.dirname(base), parent); await fs.rm(base, { recursive: true, force: true }); });
  const put = async (name, text) => { const f = path.join(vault, name); await fs.mkdir(path.dirname(f), {recursive:true}); await fs.writeFile(f, text); };
  let n=0;
  const change = async (directory, extra = {}) => {
    const options = { vault, directory, backup: path.join(base, `backup-${++n}`), writersStopped:true, configureIsolation:true, ...extra };
    return migration.migrate({ ...options, expected: (await migration.inspect(options)).fingerprint });
  };
  return { base, vault, put, change };
}
